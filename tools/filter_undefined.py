"""Keep only the splat *_auto symbol assignments that no object file defines.

splat's undefined_syms_auto / undefined_funcs_auto also list symbols that the
generated assembly does define. As linker-script assignments they would pin
those symbols to their original absolute addresses and silently override the
labels, which breaks any build where code or data moves. This writes a linker
script with just the truly external addresses (BIOS RAM, fixed buffers, ...).

It also handles orphaned jump-table case labels: a function that has been
replaced by C no longer defines its .Lxxxxxxxx labels, but its old jump table
still sits in the shared asm .rodata. That table is dead (the C version has its
own), so those labels are defined as 0. Any other undefined symbol is left for
the linker to report.

Uses readelf (nm hides .L names).
Usage: python3 -I tools/filter_undefined.py READELF OUT.ld AUTO.txt [AUTO.txt...] -- OBJ...
"""
import re
import subprocess
import sys

args = sys.argv[1:]
readelf, out = args[0], args[1]
sep = args.index("--")
autos, objs = args[2:sep], args[sep + 1:]

defined, undefined = set(), set()
res = subprocess.run([readelf, "-sW", *objs], capture_output=True, text=True, check=True)
for line in res.stdout.splitlines():
    p = line.split()
    if len(p) < 8 or not p[0].endswith(":") or not p[0][:-1].isdigit():
        continue
    bind, ndx, name = p[4], p[6], p[7]
    if bind not in ("GLOBAL", "WEAK"):
        continue
    (undefined if ndx == "UND" else defined).add(name)
orphans = sorted(u for u in undefined - defined if re.fullmatch(r"\.L[0-9A-F]{8}", u))

kept, dropped = [], 0
for path in autos:
    for line in open(path):
        name = line.split("=")[0].strip()
        if not name or line.lstrip().startswith("/"):
            continue
        if name in defined:
            dropped += 1
        else:
            kept.append(line.rstrip())

with open(out, "w") as f:
    f.write("/* generated by tools/filter_undefined.py */\n" + "\n".join(kept) + "\n")
    f.write("/* case labels of jump tables orphaned by C replacements (dead data) */\n")
    for o in orphans:
        f.write(f'"{o}" = 0;\n')
print(f"{out}: {len(kept)} external symbols kept, {dropped} already defined dropped, "
      f"{len(orphans)} orphaned jump-table labels")
